"""Cell tracking correspondence loading and division-agnostic relabeling."""

import os
from typing import Dict, List

import numpy as np
from joblib import Parallel, delayed
from skimage.measure import label
from tqdm import tqdm


def get_mapping_dict(tracking_file: str, ignore_divisions=False) -> Dict[int, str]:
    """
    Extract mapping between relative numbers (RN) and absolute numbers (AN) from a tracking file.

    Parameters
    ----------
    tracking_file : str
        Path to the tracking file.
    ignore_divisions : bool
        Whether to ignore the AN of dividing cells (ex : AN 240 1 2 -> 240)

    Returns
    -------
    Dict[int,str]
        Dictionary mapping RN to AN.
    """
    mapping_dict = {}
    with open(tracking_file, "r") as file:
        lines = file.readlines()

    for line in lines:
        line = line.strip()
        split_line = line.split(" ")

        if ignore_divisions:
            relative = split_line[0]
            absolute = split_line[1]
            mapping_dict.setdefault(relative, []).append(absolute)
        else:
            relative = split_line[0]
            absolute = " ".join(split_line[1:])
            mapping_dict.setdefault(relative, []).append(absolute)

    return mapping_dict


def get_mapping_dicts(
    ct_folder_path: str, ref_movie: np.ndarray, ignore_divisions=False
) -> list:
    """
    Import tracking files as a list of dictionaries.

    Parameters
    ----------
    ct_folder_path : str
        Path to the cell tracking folder.
    ref_movie : np.ndarray
        Reference movie array.

    Returns
    -------
    list
        List of tracking dictionaries.
    """
    tracking_files = [
        os.path.join(ct_folder_path, f"correspondence_{i + 1}.txt")
        for i in range(ref_movie.shape[0])
    ]
    list_tracking_dict = Parallel(n_jobs=-1, verbose=0)(
        delayed(get_mapping_dict)(tracking_file, ignore_divisions)
        for i, tracking_file in tqdm(enumerate(tracking_files))
    )
    return list_tracking_dict


def relabel_movie(
    skeleton_movie: np.ndarray, mapping_dicts: List[Dict[int, int]]
) -> np.ndarray:
    """
    Relabel a movie using a list of mapping dictionaries.

    Parameters
    ----------
    skeleton_movie : np.ndarray
        The skeletonized movie to be relabeled.
    mapping_dicts : List[Dict[int, int]]
        List of mapping dictionaries generated by the `import_tracking_folder` function.

    Returns
    -------
    np.ndarray
        The relabeled movie.
    """
    # Use parallel processing to relabel each frame in the skeleton movie
    relabeled_frames = Parallel(n_jobs=-1, verbose=0)(
        delayed(relabel_frame)(skeleton_movie[i], mapping_dicts[i])
        for i in tqdm(range(len(mapping_dicts)))
    )

    return np.stack(relabeled_frames)


def relabel_frame(skeleton_img, mapping_dict: Dict[int, int]) -> np.ndarray:
    """
    Relabel the frame based on a given mapping dictionary.

    Parameters
    ----------
    skeleton_img : np.ndarray
        The skeletonized image to be relabeled.
    mapping_dict : Dict[int, int]
        A dictionary mapping from old labels to new labels.

    Returns
    -------
    np.ndarray
        The relabeled frame.

    Notes
    -----
    The function assumes that the input image is skeletonized and that the
    mapping dictionary provides a list as values where the last item is the
    new label.
    """

    # Label the transposed skeleton image using 4-connectivity
    temp_labels = label(skeleton_img.T, connectivity=1)

    # Define a lambda function to get the new label from the mapping dictionary
    def get_new_label(x):
        return mapping_dict.get(x, [0])[-1]

    # Vectorize the lambda function and apply it to get the new labels
    relabeled_img = np.vectorize(get_new_label, otypes=[np.uint16])(temp_labels)

    return relabeled_img.T
